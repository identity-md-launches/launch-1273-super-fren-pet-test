#!/usr/bin/env python3
"""Validate delivered PNGs and make true-size wallet previews, offline.

The artwork is generated by image_gen. This utility only resamples existing
pixels for the requested export sizes and composites inspection thumbnails.
PyPNG 0.20220715.0 is vendored under tools/vendor with its licence.
"""
from pathlib import Path
import argparse
import sys

sys.path.insert(0, str(Path(__file__).parent / "vendor"))
import png

ROOT = Path(__file__).resolve().parents[1]


def read(path):
    width, height, rows, info = png.Reader(filename=str(path)).asRGB8()
    assert not info.get("alpha"), "Expected opaque RGB artwork"
    return width, height, [bytearray(row) for row in rows]


def write(path, rows):
    with Path(path).open("wb") as stream:
        png.Writer(len(rows[0]) // 3, len(rows), greyscale=False).write(stream, rows)


def weights(source, target):
    result = []
    for index in range(target):
        left, right = index * source, (index + 1) * source
        result.append([
            (pixel, min(right, (pixel + 1) * target) - max(left, pixel * target))
            for pixel in range(left // target, (right - 1) // target + 1)
        ])
    return result


def resize(rows, size):
    """Separable area resampling; no synthesis, drawing, or external libraries."""
    height, width = len(rows), len(rows[0]) // 3
    wx, wy = weights(width, size), weights(height, size)
    horizontal = []
    for row in rows:
        scaled = bytearray(size * 3)
        for x, contributions in enumerate(wx):
            for channel in range(3):
                scaled[3 * x + channel] = (
                    sum(row[3 * pixel + channel] * weight for pixel, weight in contributions)
                    + width // 2
                ) // width
        horizontal.append(scaled)
    output = []
    for contributions in wy:
        row = bytearray(size * 3)
        for x in range(size * 3):
            row[x] = (sum(horizontal[pixel][x] * weight for pixel, weight in contributions) + height // 2) // height
        output.append(row)
    return output


def preview(images):
    # Each column, in file order: 64px square, 64px circle, 32px circle.
    # Top row is light; bottom row dark. No enlargement of the inspection sizes.
    width, height = 960, 208
    canvas = [bytearray(([250, 250, 247] if y < 104 else [18, 24, 22]) * width) for y in range(height)]
    for index, rows in enumerate(images):
        small, tiny = resize(rows, 64), resize(rows, 32)
        for y0 in (20, 124):
            for dx, bitmap, circle in ((12, small, False), (82, small, True), (152, tiny, True)):
                size = len(bitmap)
                x0 = index * 192 + dx
                top = y0 + (64 - size) // 2
                for y, row in enumerate(bitmap):
                    for x in range(size):
                        if not circle or (x + 0.5 - size / 2) ** 2 + (y + 0.5 - size / 2) ** 2 <= (size / 2) ** 2:
                            canvas[top + y][3 * (x0 + x):3 * (x0 + x) + 3] = row[3 * x:3 * x + 3]
    return canvas


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export", nargs=2, metavar=("GENERATED_PNG", "OUTPUT_PNG"))
    args = parser.parse_args()
    if args.export:
        width, height, rows = read(args.export[0])
        assert width == height
        write(args.export[1], resize(rows, 1024))
        print(f"Exported {args.export[1]}: 1024x1024 RGB PNG")
        return
    images = []
    for index in range(1, 6):
        path = ROOT / "logos" / f"logo-{index}.png"
        width, height, rows = read(path)
        assert (width, height) == (1024, 1024), path
        images.append(rows)
        print(f"PASS {path.relative_to(ROOT)}: {width}x{height}, opaque")
    logo = ROOT / "artifacts/logo.png"
    assert logo.read_bytes() == (ROOT / "logos/logo-2.png").read_bytes()
    write(ROOT / "logos/preview.png", preview(images))
    print("PASS artifacts/logo.png matches selected image-generated option 2")
    print("Preview: logos/preview.png (options 1–5; 64px squares, 64px circles, 32px circles)")


if __name__ == "__main__":
    main()
